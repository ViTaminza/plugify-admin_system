#pragma once
// Engine side of the admin_system plugin: the ported cs2-admin_system (commands, chat, menus,
// punishment application, reconcile) on native s2sdk + plgdb.
//
// Everything here runs on the game thread: the plugify update pump (OnPluginUpdate), s2sdk
// listeners, console/chat callbacks and menu requests. No locking is needed; nothing blocks on the
// database except CreateSchema() at plugin start.
//
// Layout of the glue:
//   plugin.cpp    lifecycle, s2sdk listeners, reconcile, the admin_core hook bodies, notifications
//                 and the exported methods (IAdminApi)
//   commands.cpp  every console/chat command of the original + the as_status report
//   menus.cpp     the category/item registry and the whole admin menu (punishments flows)
//   admin_guards  the plugin's own s2sdk guards (map gate, slot/controller checks, owner identity,
//                 the Pisex printers) - docs/PLUGIN_STANDARD.md §7: no pisexcompat
//   admin_menus   the native s2sdk menu layer (deferred queue, MenuId 0 reservation, A7 teardown)
//   admin_config  the engine-free file half (candidate order, core.ini/sorting.ini/databases.cfg/
//                 phrases parsers, language chain)
//   admin_core    the engine-free database/admin model (unchanged, unit-tested)
//
// The exported methods use the callback typedefs of the generated headers
// (<admin_system/admin_system.hpp>, generated by bin/plugify-gen) - the same types the consumer
// headers hand to modules, so the boundary is checked by the compiler. The generated *binding
// slots* (__admin_system_*) stay null in this plugin: it implements the API, it never calls it.

