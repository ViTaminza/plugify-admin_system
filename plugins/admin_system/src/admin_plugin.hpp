#pragma once
// Engine side of the admin_system plugin: the ported cs2-admin_system (commands, chat, menus,
// punishment application, reconcile) on top of admin_core + libs/pisexcompat.
//
// Everything here runs on the game thread: the plugify update pump (OnPluginUpdate), s2sdk
// listeners, console/chat callbacks, timers and menu callbacks. No locking is needed; nothing
// blocks on the database except CreateSchema() at plugin start.
//
// Layout of the glue:
//   plugin.cpp    lifecycle, config/phrase/database loading, s2sdk listeners, reconcile, the
//                 admin_core hook bodies, notifications and the exported methods (IAdminApi)
//   commands.cpp  every console/chat command of the original + the as_status report
//   menus.cpp     the category/item registry and the whole admin menu (punishments flows)
//
// The exported methods use the callback typedefs of the generated headers
// (<admin_system/admin_system.hpp>, generated by bin/plugify-gen) - the same types the consumer
// headers hand to modules, so the boundary is checked by the compiler. The generated *binding
// slots* (__admin_system_*) stay null in this plugin: it implements the API, it never calls it.

#include <array>
#include <chrono>
#include <cstdint>
#include <deque>
#include <map>
#include <memory>
#include <string>
#include <string_view>
#include <vector>

#include <plg/plugin.hpp>
#include <plg/string.hpp>
#include <s2sdk/s2sdk.hpp>

#include <pisex/pisex.hpp>

#include <plgdb/db.hpp>

#include <admin_system/admin_system.hpp>

#include "admin_core.hpp"

namespace admin_system {

inline constexpr int32_t kMaxSlots = 64;
inline constexpr int32_t kPunishTypeCount = 4;

// --- menu registry (the mCategories / Item of the original) ----------------------------
struct MenuItem {
	std::string identity;
	std::string name;     // phrase key, translated when the menu is built
	std::string category;
	std::vector<std::string> flags; // '|' separated in the API, empty = no extra check
	ItemDisplayCallback display = nullptr;
	ItemSelectCallback select = nullptr;
};

struct MenuCategory {
	std::string identity;
	std::string name; // phrase key
	CategoryDisplayCallback display = nullptr;
	std::map<std::string, MenuItem, std::less<>> items;
};

// The offline players the menu offers for offline punishments (g_mOfflineUsers of the original).
struct OfflineUser {
	uint64_t steamid = 0;
	std::string name;
	std::array<bool, kPunishTypeCount> punished{};
	std::array<uint64_t, kPunishTypeCount> admin{};
};

// The pending "own reason" state of the menu flow (g_bOwnReason / g_iTarget / ... of the original).
struct OwnReasonState {
	bool active = false;
	uint64_t target = 0;
	int type = RT_BAN;
	bool offline = false;
};

// --- the plugin -----------------------------------------------------------------------
class AdminPlugin final : public plg::Plugin {
public:
	// --- lifecycle -------------------------------------------------------------------
	plg::PluginResult OnPluginStart() override;
	plg::PluginResult OnPluginUpdate(std::chrono::milliseconds dt) override;
	plg::PluginResult OnPluginEnd() override;

	// --- engine side (game thread) -----------------------------------------------------
	void HandleClientAuthenticated(int32_t playerSlot, uint64_t steamid);
	void HandleClientDisconnect(int32_t playerSlot);
	// Once per second: loads the rights/punishments of players that appeared without an
	// OnClientAuthenticated event (it is not delivered reliably) and drops gone slots.
	void ReconcileSlots();
	// Once per second: the original's expiry timer (punishments, admin rights) + announcements.
	void OnSecondTick();
	// The original's OnChatPre listener: own-reason capture and the gag/silence chat block.
	bool OnChatPre(int32_t playerSlot, const char* content, bool team);

	// --- admin_core hooks ---------------------------------------------------------------
	void HandleAdminLoaded(int32_t slot, const AdminRecord& admin);
	void HandlePunishmentsLoaded(int32_t slot, const PunishmentLoadOutcome& outcome);
	void HandlePlayerPunish(int32_t slot, int32_t type, int32_t time, const std::string& reason, int32_t adminRef);
	void HandleOfflinePlayerPunish(const std::string& steamid64, const std::string& name, int32_t type, int32_t time,
								   const std::string& reason, int32_t adminRef);
	void HandlePlayerUnpunish(int32_t slot, int32_t type, int32_t adminRef);
	void HandleOfflinePlayerUnpunish(const std::string& steamid64, int32_t type, int32_t adminRef);
	void HandleCoreError(std::string_view message);

	// --- configuration -------------------------------------------------------------------
	const Config& Cfg() const { return m_config; }
	AdminCore& Core() { return *m_core; }
	// nullptr until the database is up (the exported methods answer neutral values then).
	AdminCore* CoreOrNull() { return m_core.get(); }
	const AdminCore* CoreOrNull() const { return m_core.get(); }
	const AdminRecord* FindAdmin(int32_t slot) const;
	// The connection settings exported to the modules (driver/host/port/... for their own plgdb).
	const plgdb::Config& DatabaseConfig() const { return m_dbConfig; }
	// Phrase lookup (the g_vecPhrases map of the original; missing keys print as the key).
	const char* Phrase(const char* key) const { return pisex::GetPhraseCStr(key); }
	std::vector<std::string>& SortCategories() { return m_sortCategories; }
	std::map<std::string, std::vector<std::string>, std::less<>>& SortItems() { return m_sortItems; }
	bool IsCoreLoaded() const { return m_coreLoaded; }

	// --- API surface used by the exports and the menu/command code -------------------------
	void RegisterCategory(const plg::string& identity, const plg::string& name, CategoryDisplayCallback callback);
	void RegisterItem(const plg::string& identity, const plg::string& name, const plg::string& category,
					  const plg::string& flags, ItemDisplayCallback display, ItemSelectCallback select);
	// HasAccessInItem / HasAccessInCategory of the original.
	bool HasAccessInItem(int32_t slot, const std::string& category, const std::string& identity) const;
	bool HasAccessInCategory(int32_t slot, const std::string& category) const;

	void ShowAdminMenu(int32_t slot);
	void ShowAdminCategoryMenu(int32_t slot, const std::string& category);
	void ShowAdminLastCategoryMenu(int32_t slot);
	void ShowAdminItemMenu(int32_t slot, const std::string& category, const std::string& identity);
	void CloseAdminMenu(int32_t slot) const;
	void SetLastCategory(int32_t slot, const std::string& category);
	// The punishment flows of menus.cpp (the ShowPunishMenu family of the original).
	void ShowPunishTypeMenu(int32_t slot, bool offline, bool unpunish);
	void ShowPunishMenu(int32_t slot, int32_t type);
	void ShowReasonsMenu(int32_t slot, uint64_t target, int32_t type, bool offline);
	void ShowTimesMenuFor(int32_t slot, uint64_t target, int32_t type, const std::string& reason, bool offline,
						  const std::string& ownReason);
	void ShowUnpunishMenu(int32_t slot, int32_t type);
	void ShowPunishOfflineMenu(int32_t slot, int32_t type);
	void ShowUnpunishOfflineMenu(int32_t slot, int32_t type);
	// Marks an offline entry as punished and returns its name (the menu flow of the original).
	std::string MarkOfflinePunished(uint64_t steamid, int32_t type, int32_t admin);
	bool IsAdminSlot(int32_t slot) const;
	const MenuItem* FindItem(const std::string& category, const std::string& identity) const;
	std::string CategoryLabel(int32_t slot, const MenuCategory& category) const;
	std::string ItemLabel(int32_t slot, const MenuItem& item) const;
	// mm_as_reload_config: core.ini, sorting.ini and the phrases again (the database connection is
	// fixed at plugin start).
	void ReloadConfig();

	// --- punishment flows (the core applies them, the plugin drives the menus/commands) ------
	// AddPlayerPunishment / AddOfflinePlayerPunishment with the chat notices of the original.
	bool AddPlayerPunishment(const PlayerIdentity& player, int32_t type, int32_t time, const std::string& reason,
							 int32_t adminRef, bool notify, bool db);
	bool AddOfflinePlayerPunishment(const std::string& steamid64, const std::string& name, int32_t type, int32_t time,
									const std::string& reason, int32_t adminRef);
	bool TryAddPunishment(const PlayerIdentity& player, int32_t type, int32_t time, const std::string& reason,
						  int32_t adminRef, bool notify);
	void TryAddOfflinePunishment(const std::string& steamid64, const std::string& name, int32_t type, int32_t time,
								 const std::string& reason, int32_t adminRef);
	void RemovePlayerPunishment(int32_t slot, int32_t type, int32_t adminRef, bool notify);
	void TryRemovePunishment(int32_t slot, int32_t type, int32_t adminRef);
	void RemoveOfflinePlayerPunishment(const std::string& steamid64, int32_t type, int32_t adminRef);
	// The ban half of the original: kick after ban_delay (immediate for the connect path);
	// steamid is the punished player, so the kick cannot hit a later occupant of the slot.
	void KickForBan(int32_t slot, bool delayed, uint64_t steamid);

	// The steamid known for a slot (tracked from the reconcile/authentication).
	uint64_t SlotSteamId(int32_t slot) const;
	// The full identity the core needs (slot + steamid + name + ip).
	PlayerIdentity IdentityOf(int32_t slot) const;
	bool IsSlotHuman(int32_t slot) const;

	// --- admin maintenance (the AddPlayerAdmin/RemovePlayerAdmin exports) ---------------------
	// AddAdmin()/RemoveAdmin() of the original: the database half is in admin_core, this resolves
	// the online slots of the steamid and reloads their rights.
	void AddAdmin(std::string name, std::string steamid64, std::string flags, int immunity, int expireSeconds,
				  int64_t groupId, std::string comment, bool db);
	void RemoveAdmin(const std::string& steamid64, bool db);

	// --- offline user list (menus) -----------------------------------------------------------
	std::deque<OfflineUser>& OfflineUsers() { return m_offlineUsers; }
	OwnReasonState& OwnReason(int32_t slot) { return m_ownReasons[static_cast<size_t>(slot)]; }

	// --- actions / callbacks (the IAdminApi registration pairs) -------------------------------
	void SendAction(int32_t slot, const std::string& action, const std::string& param);
	void BroadcastCoreLoaded();

	// Callback registries. The original keyed listeners by plugin id; here every registration is a
	// function pointer (each consumer plugin has exactly one per event) - registering the same
	// pointer twice replaces nothing, unregistering removes it.
	std::vector<AdminConnectedCallback>& AdminConnectedListeners() { return m_onAdminConnected; }
	std::vector<CoreLoadedCallback>& CoreLoadedListeners() { return m_onCoreLoaded; }
	std::vector<CategoryRegisterCallback>& CategoryRegisterListeners() { return m_onCategoryRegister; }
	std::vector<ActionCallback>& ActionListeners() { return m_onAction; }
	std::vector<PlayerPunishCallback>& PlayerPunishListeners() { return m_onPlayerPunish; }
	std::vector<OfflinePlayerPunishCallback>& OfflinePlayerPunishListeners() { return m_onOfflinePlayerPunish; }
	std::vector<PlayerUnpunishCallback>& PlayerUnpunishListeners() { return m_onPlayerUnpunish; }
	std::vector<OfflinePlayerUnpunishCallback>& OfflinePlayerUnpunishListeners() { return m_onOfflinePlayerUnpunish; }
	std::vector<PlayerPunishPreCallback>& PlayerPunishPreListeners() { return m_onPlayerPunishPre; }
	std::vector<OfflinePlayerPunishPreCallback>& OfflinePlayerPunishPreListeners() { return m_onOfflinePlayerPunishPre; }

	// --- as_status (console report) --------------------------------------------------------------
	void PrintStatus(int32_t caller, s2sdk::ConCommandContext context);

private:
	struct SlotState {
		uint64_t steamid = 0; // steamid the slot's rights/punishments were requested for
		bool requested = false;
		bool punishmentsLoaded = false; // the load answered (successfully or not)
		std::string name;
		std::chrono::steady_clock::time_point requestedAt{};
	};

	// --- startup steps ---------------------------------------------------------------------
	bool EnsureCore();      // database + schema + config + phrases (startup only)
	bool LoadCoreConfig();
	bool LoadSortingIni();
	bool LoadPhrasesFiles();
	void RegisterCoreMenus();
	// static_name = 1: forces the database name of admins (the original's jointeam/round_start hooks).
	void RegisterStaticNameHooks();

	// --- notifications of the original (SendPunishmentNotification) --------------------------
	void SendPunishmentNotification(int32_t slot, int32_t type, int32_t time, const std::string& reason, int32_t adminRef);
	void SendUnpunishmentNotification(int32_t slot, int32_t type, int32_t adminRef) const;
	// "1d 2h 3m" from an absolute expiry (FormatTime of the original).
	std::string FormatTime(int64_t expires) const;

	void ClearSlot(int32_t slot, const char* reason);
	std::string AdminName(int32_t adminRef) const;

	Config m_config;
	plgdb::Config m_dbConfig;
	std::unique_ptr<plgdb::Database> m_db;
	std::unique_ptr<AdminCore> m_core;
	bool m_coreLoaded = false;

	std::map<std::string, MenuCategory, std::less<>> m_categories;
	std::vector<std::string> m_sortCategories;
	std::map<std::string, std::vector<std::string>, std::less<>> m_sortItems;
	std::array<std::string, kMaxSlots> m_lastCategory;

	std::deque<OfflineUser> m_offlineUsers;
	std::array<OwnReasonState, kMaxSlots> m_ownReasons{};

	std::array<SlotState, kMaxSlots> m_slots{};
	std::chrono::milliseconds m_sinceReconcile{0};
	std::chrono::milliseconds m_updateAccumulator{0};
	bool m_listenersRegistered = false;
	pisex::CTimer* m_secondTimer = nullptr;

	std::vector<AdminConnectedCallback> m_onAdminConnected;
	std::vector<CoreLoadedCallback> m_onCoreLoaded;
	std::vector<CategoryRegisterCallback> m_onCategoryRegister;
	std::vector<ActionCallback> m_onAction;
	std::vector<PlayerPunishCallback> m_onPlayerPunish;
	std::vector<OfflinePlayerPunishCallback> m_onOfflinePlayerPunish;
	std::vector<PlayerUnpunishCallback> m_onPlayerUnpunish;
	std::vector<OfflinePlayerUnpunishCallback> m_onOfflinePlayerUnpunish;
	std::vector<PlayerPunishPreCallback> m_onPlayerPunishPre;
	std::vector<OfflinePlayerPunishPreCallback> m_onOfflinePlayerPunishPre;
};

extern AdminPlugin g_adminPlugin;

// --- shared helpers (plugin.cpp) -----------------------------------------------------------
std::string ToString(std::string_view view);
// "%s" for a std::string; keeps the call sites readable.
inline const char* CStr(const std::string& text) {
	return text.c_str();
}
// Logs through plg::Log (never throws, no-op when the module did not set the slot).
void LogMessage(std::string_view message, plg::Severity severity);
void LogInfo(std::string_view message);
void LogError(std::string_view message);
// The original split the item flag list on '|'.
std::vector<std::string> ParsePipeList(std::string_view text);

// --- commands.cpp ---------------------------------------------------------------------------
// Registers every console/chat command of the original plus as_status (OnPluginStart).
void RegisterCommands();
// Removes the s2sdk console command as_status again (OnPluginEnd; the pisexcompat commands are
// dropped by pisex::Shutdown()).
void UnregisterCommands();
// The punishment/unpunishment command bodies of the original (TotalCommand + friends).
void CommandPunish(int32_t admin, int32_t type, const char* permission, const pisex::CommandArgs& args);
void CommandUnpunish(int32_t admin, int32_t type, const char* permission, const pisex::CommandArgs& args);
void CommandAddAdmin(int32_t admin, const pisex::CommandArgs& args, bool remove, bool console);
void CommandAddGroup(int32_t admin, const pisex::CommandArgs& args, bool console);
void CommandRemoveGroup(int32_t admin, const pisex::CommandArgs& args, bool console);
void CommandReloadConfig(int32_t admin);
void CommandReloadAdmin(int32_t admin, const pisex::CommandArgs& args);
void CommandReloadPunish(int32_t admin, const pisex::CommandArgs& args);
// mm_add_group / mm_remove_group call the core directly; the group notices live here too.
void AddGroupCore(int32_t admin, const char* name, const char* flags, int immunity, bool console);

// --- menus.cpp ------------------------------------------------------------------------------
// The select callbacks of the core's own punishment items.
void AdminSelectPunish(int32_t slot, const plg::string& category, const plg::string& identity, const plg::string& item);
void AdminSelectUnpunish(int32_t slot, const plg::string& category, const plg::string& identity, const plg::string& item);
void AdminSelectPunishOffline(int32_t slot, const plg::string& category, const plg::string& identity,
							  const plg::string& item);
void AdminSelectUnpunishOffline(int32_t slot, const plg::string& category, const plg::string& identity,
								const plg::string& item);

} // namespace admin_system
